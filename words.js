function buildWordLists() {
    const core = new Set();
    const all = new Set();

    function addList(list, toCore) {
        list.forEach(w => {
            const n = stripAccents(w).replace(/[^A-Z]/g, '');
            if (!okWord(n)) return;
            all.add(n);
            if (toCore) core.add(n);
        });
    }

    addList(WORDS_FAMILY, true);
    addList(WORDS_COLORS, true);
    addList(WORDS_JOBS, true);
    addList(WORDS_BODY, true);
    addList(WORDS_OBJECTS, true);
    addList(WORDS_COUNTRIES, true);
    addList(WORDS_TRAITS, true);
    addList(WORDS_ANIMALS, true);
    addList(WORDS_SKY, true);
    addList(WORDS_NATURE, true);
    addList(WORDS_GENERAL, true);
    addList(WORDS_COMMON_EXTRA, true);
    addList(ADJECTIVE_BASES, true);
    addList(ADJECTIVE_FORMS, true);
    addList(ADJECTIVE_RELATED, true);
    addList(NOUN_COMMON, true);
    addList(WORDS_EXPANSAO, true);
    addList(WORDS_EXPANSAO2, true);
    addList(WORDS_TEMATICO_EXTRA, true);
    addList(CORE_WORDS, true);

    function addForms(forms) {
        forms.forEach(f => {
            const n = stripAccents(f).replace(/[^A-Z]/g, '');
            if (okWord(n)) all.add(n);
        });
    }

    // Irregulares de gênero
    const GENDER_IRREGULAR = {
        BOM: ['BOM','BOA','BONS','BOAS'],
        MAU: ['MAU','MA','MAUS','MAS'],
        SAO: ['SAO','SA','SAOS','SAS'],
        CAO: ['CAO','CA','CAES'],
        AO: ['AO','A','AOS','AS'],
        UM: ['UM','UMA','UNS','UMAS'],
        TODO: ['TODO','TODA','TODOS','TODAS'],
        NENHUM: ['NENHUM','NENHUMA','NENHUNS','NENHUMAS'],
        ALGUM: ['ALGUM','ALGUMA','ALGUNS','ALGUMAS'],
        MUITO: ['MUITO','MUITA','MUITOS','MUITAS'],
        POUCO: ['POUCO','POUCA','POUCOS','POUCAS'],
        OUTRO: ['OUTRO','OUTRA','OUTROS','OUTRAS'],
        MESMO: ['MESMO','MESMA','MESMOS','MESMAS'],
        PROPRIO: ['PROPRIO','PROPRIA','PROPRIOS','PROPRIAS'],
        PRIMEIRO: ['PRIMEIRO','PRIMEIRA','PRIMEIROS','PRIMEIRAS'],
        TERCEIRO: ['TERCEIRO','TERCEIRA','TERCEIROS','TERCEIRAS'],
        EUROPEU: ['EUROPEU','EUROPEIA','EUROPEUS','EUROPEIAS'],
        JUDEU: ['JUDEU','JUDIA','JUDEUS','JUDIAS'],
        CRU: ['CRU','CRUA','CRUS','CRUAS'],
        NU: ['NU','NUA','NUS','NUAS'],
        BRINCALHAO: ['BRINCALHAO','BRINCALHONA','BRINCALHOES','BRINCALHONAS'],
        CAMPEAO: ['CAMPEAO','CAMPEA','CAMPEOES','CAMPEAS'],
        ANCIAO: ['ANCIAO','ANCIA','ANCIAOS','ANCIAS'],
        ORFAO: ['ORFAO','ORFA','ORFAOS','ORFAS'],
        SOLTEIRO: ['SOLTEIRO','SOLTEIRA','SOLTEIROS','SOLTEIRAS'],
        TRABALHADOR: ['TRABALHADOR','TRABALHADORA','TRABALHADORES','TRABALHADORAS'],
        VENDEDOR: ['VENDEDOR','VENDEDORA','VENDEDORES','VENDEDORAS'],
        JOGADOR: ['JOGADOR','JOGADORA','JOGADORES','JOGADORAS'],
        VENCEDOR: ['VENCEDOR','VENCEDORA','VENCEDORES','VENCEDORAS'],
        PERDEDOR: ['PERDEDOR','PERDEDORA','PERDEDORES','PERDEDORAS'],
        PROFESSOR: ['PROFESSOR','PROFESSORA','PROFESSORES','PROFESSORAS'],
        DOUTOR: ['DOUTOR','DOUTORA','DOUTORES','DOUTORAS'],
        DIRETOR: ['DIRETOR','DIRETORA','DIRETORES','DIRETORAS'],
        TRAIDOR: ['TRAIDOR','TRAIDORA','TRAIDORES','TRAIDORAS'],
        PECADOR: ['PECADOR','PECADORA','PECADORES','PECADORAS']
    };

    function expandGender(word) {
        const w = stripAccents(word).replace(/[^A-Z]/g, '');
        if (!okWord(w)) return [];
        if (GENDER_IRREGULAR[w]) return GENDER_IRREGULAR[w].filter(okWord);

        const out = new Set([w]);
        // -oso/-osa, -ivo/-iva, -ado/-ada, -ido/-ida, -eiro/-eira, -ento/-enta
        if (/(OSO|IVO|ADO|IDO|EIRO|ENTO|ESCO|ICO|ARIO|ORIO|UDO|ADO)$/.test(w) ||
            (w.endsWith('O') && !w.endsWith('AO') && !w.endsWith('EO'))) {
            const fem = w.slice(0, -1) + 'A';
            out.add(fem);
            out.add(w + 'S');
            out.add(fem + 'S');
        } else if (w.endsWith('A') && w.length > 3 && !w.endsWith('ISTA') && !w.endsWith('EZA') && !w.endsWith('URA')) {
            const masc = w.slice(0, -1) + 'O';
            out.add(masc);
            out.add(w + 'S');
            out.add(masc + 'S');
        } else if (w.endsWith('OR')) {
            out.add(w + 'A');
            out.add(w + 'ES');
            out.add(w + 'AS');
        } else if (w.endsWith('AO') && w.length > 3) {
            out.add(w.slice(0, -2) + 'A');
            out.add(w.slice(0, -2) + 'ONA');
            out.add(w.slice(0, -2) + 'OES');
            out.add(w.slice(0, -2) + 'ONAS');
            out.add(w.slice(0, -2) + 'AES');
        } else if (w.endsWith('U') && w.length >= 3 && !w.endsWith('EU')) {
            out.add(w + 'A');
            out.add(w + 'S');
            out.add(w + 'AS');
        } else if (w.endsWith('EU')) {
            out.add(w.slice(0, -2) + 'EIA');
            out.add(w + 'S');
            out.add(w.slice(0, -2) + 'EIAS');
        } else if (w.endsWith('L')) {
            // fiel → fieis; fácil → fáceis (FACIL → FACEIS)
            if (w.endsWith('IL')) out.add(w.slice(0, -2) + 'EIS');
            else out.add(w.slice(0, -1) + 'IS');
        } else if (w.endsWith('Z')) {
            out.add(w.slice(0, -1) + 'ZES');
        } else if (w.endsWith('R') || w.endsWith('S') || w.endsWith('Z')) {
            // já plural-ish
        } else if (!w.endsWith('S') && !w.endsWith('M')) {
            out.add(w + 'S'); // alegre → alegres; feliz handled separately
        }
        if (w.endsWith('Z') && w.length >= 4) {
            // feliz → felizes
            out.add(w + 'ES');
        }
        return [...out].filter(okWord);
    }

    // Expande todos os adjetivos com M/F/plural
    ADJECTIVE_BASES.forEach(adj => {
        expandGender(adj).forEach(g => {
            all.add(g);
            core.add(g);
        });
    });
    ADJECTIVE_FORMS.forEach(adj => {
        const n = stripAccents(adj).replace(/[^A-Z]/g, '');
        if (okWord(n)) { all.add(n); core.add(n); }
        expandGender(n).forEach(g => { all.add(g); core.add(g); });
    });
    NOUN_COMMON.forEach(noun => {
        const n = stripAccents(noun).replace(/[^A-Z]/g, '');
        if (okWord(n)) { all.add(n); core.add(n); }
        expandGender(n).forEach(g => { all.add(g); core.add(g); });
    });
    Object.keys(GENDER_IRREGULAR).forEach(k => addForms(GENDER_IRREGULAR[k]));

    [...all].forEach(w => addForms(expandGender(w)));

    [...new Set(VERBS_AR)].filter(v => stripAccents(v).endsWith('AR')).forEach(v => addForms(conjugateAR(v)));
    [...new Set(VERBS_ER)].filter(v => stripAccents(v).endsWith('ER')).forEach(v => addForms(conjugateER(v)));
    [...new Set(VERBS_IR)].filter(v => stripAccents(v).endsWith('IR')).forEach(v => addForms(conjugateIR(v)));
    addForms(IRREGULAR_FORMS);

    Object.keys(WORD_FAMILIES).forEach(key => {
        addForms(WORD_FAMILIES[key]);
        WORD_FAMILIES[key].forEach(w => {
            const n = stripAccents(w).replace(/[^A-Z]/g, '');
            if (okWord(n)) {
                core.add(n); all.add(n);
                expandGender(n).forEach(g => { core.add(g); all.add(g); });
            }
        });
    });

    [
        ...WORDS_FAMILY, ...WORDS_COLORS.slice(0, 40),
        ...WORDS_NATURE.slice(0, 60),
        ...ADJECTIVE_BASES.slice(0, 80),
        ...ADJECTIVE_FORMS.slice(0, 120),
        ...NOUN_COMMON.slice(0, 80),
        'HONESTO','HONESTA','HONESTOS','HONESTAS','HONRA','HONRADO','HONRADA',
        'DESONESTO','DESONESTA','DESONESTOS','DESONESTAS','SINCERO','SINCERA',
        'MENTIROSO','MENTIROSA','JUSTO','JUSTA','LEAL','FIEL','INTEGRO','INTEGRA',
        'FRANCO','FRANCA','VERDADEIRO','VERDADEIRA','FALSO','FALSA','VERDADE','MENTIRA',
        'BRASIL','PORTUGAL','MEDICO','PROFESSOR','CABECA','OLHO','BOCA','MAO',
        'CASA','MESA','COPO','CHAVE','PAU','PAUS','MADEIRA','TRONCO','GALHO',
        'AZUL','VERDE','VERMELHO','AMARELO','PRETO','BRANCO','CAMILA','AMOR',
        'AMA','AMO','AMAR','GATO','GATA','BAR','DOR','DAR','SONO','SONHO','SONHA',
        'MIA','MIO','MIOU','MIADO','BATER','BATE','BATA','LATIR','LATE','CAO',
        'MEU','MINHA','SEU','SUA','TEU','TUA','NOSSO','NOSSA',
        'ADOTAR','ADOTA','ADOTO','ADOTEI','ADOTOU','ADOTADO','ADOTADA','ADOCAO',
        'SARDA','SARDAS','SARDENTO','SARDENTA','FLOR','ARVORE','FOLHA','RIO','MAR',
        'MATO','FLORESTA','PEDRA','AREIA','CHUVA','NUVEM','VENTO','SOL','LUA',
        'LAMURIA','LAMURIAR','LAMURIO','LAMURIEI','LAMURIOU','LAMURIADO','LAMENTO',
        'BONITO','BONITA','LINDO','LINDA','FEIO','FEIA','FELIZ','TRISTE','RICO','RICA',
        'BOM','BOA','BONS','BOAS','ALTO','ALTA','BAIXO','BAIXA','NOVO','NOVA',
        'VELHO','VELHA','GRANDE','PEQUENO','PEQUENA','FORTE','FRACO','FRACA',
        'HOMEM','MULHER','AMIGO','AMIGA','DIA','NOITE','AGUA','FOGO','COMIDA'
    ].forEach(w => {
        const n = stripAccents(w).replace(/[^A-Z]/g, '');
        if (okWord(n)) { core.add(n); all.add(n); }
    });

    return {
        CORE_WORDS: [...core],
        COMMON_WORDS: [...all],
        COUNTS: {
            nature: WORDS_NATURE.length,
            objects: WORDS_OBJECTS.length,
            animals: WORDS_ANIMALS.length,
            traits: WORDS_TRAITS.length,
            adjectives: ADJECTIVE_BASES.length + ADJECTIVE_FORMS.length,
            nouns: NOUN_COMMON.length,
            expansao: WORDS_EXPANSAO.length,
            sky: WORDS_SKY.length,
            total: 0
        }
    };
}

const _lists = buildWordLists();
const CORE_WORDS_FINAL = _lists.CORE_WORDS;
const COMMON_WORDS = _lists.COMMON_WORDS;
_lists.COUNTS.total = COMMON_WORDS.length;

// Sementes do mapa: 4–5 letras usuais
const MAP_SEEDS = CORE_WORDS_FINAL.filter(w =>
    w.length >= 4 && w.length <= 5 && w !== 'CAMILA'
);

// Log útil no console (dev)
if (typeof console !== 'undefined') {
    console.info('[Wordmila] palavras no dicionário:', COMMON_WORDS.length,
        '| sementes mapa:', MAP_SEEDS.length,
        '| categorias:', _lists.COUNTS);
}
