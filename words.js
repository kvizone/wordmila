function stripAccents(s) {
    return String(s).normalize('NFD').replace(/[\u0300-\u036f]/g, '').toUpperCase();
}

function okWord(w) {
    return /^[A-Z]+$/.test(w) && w.length >= 3 && w.length <= 12;
}

